    dobro = numero * 2
    triplo = numero * 3
    quadrado = numero ** 2
    print(f"O dobro do número informado é {dobro}")
    print(f"O triplo do número informado é {triplo}")
    print(f"O quadrado do número informado é {quadrado}")
